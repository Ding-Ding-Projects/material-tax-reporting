import { access, cp, mkdir, readdir, readFile, rm, writeFile } from "node:fs/promises";
import { relative, resolve, sep } from "node:path";
import type { Plugin } from "vite";
import {
  type ChangelogEntry,
  type DocArticle,
  buildDocsIndex,
  parseChangelog,
} from "@material-tax-reporting/surface-kernel";

async function exists(path: string): Promise<boolean> {
  try {
    await access(path);
    return true;
  } catch (error) {
    if ((error as NodeJS.ErrnoException).code === "ENOENT") {
      return false;
    }
    throw error;
  }
}

// Packages Sites metadata and migrations after Vite finishes compiling.
export function sites(): Plugin {
  let root = process.cwd();

  return {
    name: "sites",
    apply: "build",
    configResolved(config) {
      root = config.root;
    },
    async closeBundle() {
      const outputDirectory = resolve(root, "dist", ".openai");
      const hostingConfig = resolve(root, ".openai", "hosting.json");
      const drizzleSource = resolve(root, "drizzle");

      await rm(outputDirectory, { recursive: true, force: true });
      await mkdir(outputDirectory, { recursive: true });

      if (await exists(hostingConfig)) {
        await cp(hostingConfig, resolve(outputDirectory, "hosting.json"));
      }
      if (await exists(drizzleSource)) {
        await cp(drizzleSource, resolve(outputDirectory, "drizzle"), {
          recursive: true,
        });
      }
    },
  };
}

const GENERATED_HEADER = [
  "// Generated by apps/site/build/sites-vite-plugin.ts. Do not edit by hand.",
  "//",
  "// The documentation browser and the changelog viewer read this file, which is",
  "// produced from the tracked Markdown sources at build time. Regenerate it by",
  "// running the site build; editing it directly lets the site drift from the",
  "// repository it claims to describe.",
  "",
].join("\n");

/** Documentation directories that are indexed, in the order they are shown. */
const DOC_ROOTS: readonly { directory: string; area: string }[] = [
  { directory: "docs/site", area: "Website" },
  { directory: "docs/features", area: "Features" },
];

async function collectMarkdown(directory: string): Promise<string[]> {
  const found: string[] = [];
  let entries: Awaited<ReturnType<typeof readdir>>;
  try {
    entries = await readdir(directory, { withFileTypes: true });
  } catch {
    return found;
  }
  for (const entry of entries) {
    const path = resolve(directory, entry.name);
    if (entry.isDirectory()) found.push(...(await collectMarkdown(path)));
    else if (entry.name.toLowerCase().endsWith(".md")) found.push(path);
  }
  return found.sort();
}

function titleOf(markdown: string, fallback: string): string {
  const heading = /^#\s+(.+)$/m.exec(markdown);
  return heading?.[1]?.trim() ?? fallback;
}

function slugOf(repositoryPath: string): string {
  return repositoryPath.replace(/\.md$/i, "").replace(/[^A-Za-z0-9]+/g, "-").toLowerCase();
}

async function readDocArticles(repositoryRoot: string): Promise<{
  articles: DocArticle[];
  areas: Record<string, string>;
}> {
  const articles: DocArticle[] = [];
  const areas: Record<string, string> = {};
  for (const root of DOC_ROOTS) {
    const directory = resolve(repositoryRoot, root.directory);
    for (const file of await collectMarkdown(directory)) {
      const repositoryPath = relative(repositoryRoot, file).split(sep).join("/");
      const markdown = await readFile(file, "utf8");
      const slug = slugOf(repositoryPath);
      articles.push({
        slug,
        title: titleOf(markdown, repositoryPath),
        path: repositoryPath,
        markdown,
      });
      areas[slug] = root.area;
    }
  }
  return { articles, areas };
}

async function readChangelogEntries(repositoryRoot: string): Promise<ChangelogEntry[]> {
  const entries: ChangelogEntry[] = [];
  let names: string[];
  try {
    names = await readdir(repositoryRoot);
  } catch {
    return entries;
  }
  for (const name of names.sort()) {
    const match = /^CHANGELOG\.(.+)\.md$/.exec(name);
    if (!match) continue;
    const area = match[1] ?? name;
    const markdown = await readFile(resolve(repositoryRoot, name), "utf8");
    entries.push(...parseChangelog(markdown, area));
  }
  return entries;
}

async function writeIfChanged(path: string, body: string): Promise<void> {
  try {
    if ((await readFile(path, "utf8")) === body) return;
  } catch {
    /* The file does not exist yet. */
  }
  await writeFile(path, body, "utf8");
}

/**
 * Generates `app/data/docs.ts` and `app/data/changelog.ts` from the tracked
 * Markdown at build time.
 *
 * Parsing happens here, in the build, so the browser needs no runtime fetch and
 * the documentation browser works offline from the bundle. The generated files
 * are committed so a checkout is buildable and reviewable, and they are
 * rewritten on every build so they cannot drift from the sources.
 */
export function generatedContent(): Plugin {
  let root = process.cwd();

  return {
    name: "generated-content",
    configResolved(config) {
      root = config.root;
    },
    async buildStart() {
      const repositoryRoot = resolve(root, "..", "..");
      const dataDirectory = resolve(root, "app", "data");
      await mkdir(dataDirectory, { recursive: true });

      const { articles, areas } = await readDocArticles(repositoryRoot);
      const index = buildDocsIndex(articles);
      const docsBody = [
        GENERATED_HEADER,
        'import type { DocsIndex, DocsIndexEntry } from "@material-tax-reporting/surface-kernel";',
        "",
        `export const DOC_ENTRIES: DocsIndexEntry[] = ${JSON.stringify(index.articles, null, 2)};`,
        "",
        `export const DOC_AREAS: Record<string, string> = ${JSON.stringify(areas, null, 2)};`,
        "",
        `export const DOC_UNRESOLVED_LINKS: { fromSlug: string; href: string }[] = ${JSON.stringify(
          index.unresolvedLinks,
          null,
          2,
        )};`,
        "",
        "const bySlug: Record<string, DocsIndexEntry> = {};",
        "for (const entry of DOC_ENTRIES) bySlug[entry.slug] = entry;",
        "",
        "export const DOCS_INDEX: DocsIndex = {",
        "  articles: DOC_ENTRIES,",
        "  bySlug,",
        "  unresolvedLinks: DOC_UNRESOLVED_LINKS,",
        "};",
        "",
      ].join("\n");
      await writeIfChanged(resolve(dataDirectory, "docs.ts"), docsBody);

      const changelogEntries = await readChangelogEntries(repositoryRoot);
      const changelogBody = [
        GENERATED_HEADER,
        'import type { ChangelogEntry } from "@material-tax-reporting/surface-kernel";',
        "",
        `export const CHANGELOG_ENTRIES: ChangelogEntry[] = ${JSON.stringify(
          changelogEntries,
          null,
          2,
        )};`,
        "",
        `export const CHANGELOG_AREAS: string[] = ${JSON.stringify(
          [...new Set(changelogEntries.map((entry) => entry.area))].sort(),
          null,
          2,
        )};`,
        "",
        "/**",
        " * The repository this site is published from. `commitUrl` returns null for",
        " * an entry with no recorded commit identifier, and the viewer then renders no",
        " * link rather than a guessed address.",
        " */",
        'export const CHANGELOG_REPOSITORY = "";',
        "",
      ].join("\n");
      await writeIfChanged(resolve(dataDirectory, "changelog.ts"), changelogBody);
    },
  };
}
